//Relational Operators
// >
// <
// >=
// <=
// ==
// !=

#include<iostream>
using namespace std;

int main(){

    int a = 10;
    int b = 3;
    
    cout << (10>3) << endl; // greater than
    cout << (10<3) << endl; // less than
    cout << (10>=3) << endl; // greater than equal to
    cout << (10<=3) << endl; // less than equal to
    cout << (10==3) << endl; // equal to
    cout << (10!=3) << endl; // not equal to

    return 0;
}