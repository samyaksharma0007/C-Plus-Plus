//Assignment Operators
// = - equal to
// += - equal then plus with variable
// -= - equal then subtraction with variable
// *= - equal then multiplication with variable
// /= - equal then divison with variable
// %= - equal then modulus with variable

#include<iostream>
using namespace std;

int main(){
    
    int arr = 5;
    cout << arr << endl;

    arr += 10;
    cout << arr << endl;

    arr -= 8;
    cout << arr << endl;

    arr *= 2;
    cout << arr << endl;

    arr /= 3;
    cout << arr << endl;

    arr %= 5;
    cout << arr << endl;


    return 0;
}